//
// Tests the UTF-16 decoders
//

#include <dumbtest/util.hpp>
#include <sstream>

#include "include/datastream.hpp"

#define SuiteName UTF16
DefineSuite();

ImplementTest(LittleEndianSimpleDecode) {
	// "ロレム・イプサムは、ページの空白部分を埋め"
	const unsigned char s[] = {
		0xED, 0x30, 0xEC, 0x30, 0xE0, 0x30, 0xFB, 0x30, 0xA4, 0x30,
		0xD7, 0x30, 0xB5, 0x30, 0xE0, 0x30, 0x6F, 0x30, 0x01, 0x30,
		0xDA, 0x30, 0xFC, 0x30, 0xB8, 0x30, 0x6E, 0x30, 0x7A, 0x7A,
		0x7D, 0x76, 0xE8, 0x90, 0x06, 0x52, 0x92, 0x30, 0xCB, 0x57,
		0x81, 0x30
	};

	const DS::Codepoint cps[] = {
		0x30ED, 0x30EC, 0x30E0, 0x30FB, 0x30A4, 0x30D7, 0x30B5, 0x30E0,
		0x306F, 0x3001, 0x30DA, 0x30FC, 0x30B8, 0x306E, 0x7A7A, 0x767D,
		0x90E8, 0x5206, 0x3092, 0x57CB, 0x3081
	};

	std::istringstream iss{std::string{reinterpret_cast<const char*>(s)}};
	DS::UTF16LEIStream stream{iss.rdbuf()};

	for ( auto codepoint : cps ) {
		EQ(stream.Get(), codepoint);
	}
}

