#define SuiteName UTF8
DefineSuite();

ImplementTest(AsciiDecode) {
	std::string s = "The quick brown fox jumps over the lazy dog.";
	std::istringstream iss{s};
	DS::UTF8IStream stream{iss.rdbuf()};

	for ( auto c : s ) {
		EQ(stream.Get(), static_cast<DS::Codepoint>(c));
	}
}

